#!/bin/bash

echo "=== AI Vehicle Maintenance Assistant 통합 실행기 ==="
echo ""

echo "========================================================"
echo "[1단계] 백엔드 및 AI 서버(Docker) 구동 시작"
echo "========================================================"
docker compose up --build -d

echo "서버 안정화 및 AI 모델 로딩 대기 중 (15초)..."
sleep 15

echo "LLaVA 비전 모델 확인 중..."
docker exec ollama-server ollama run llava

echo ""
echo "--------------------------------------------------------"
echo " [백엔드 & AI 서버 구동 완료!]"
echo " - 백엔드(Swagger) 접속 주소: http://localhost:8000/docs"
echo "--------------------------------------------------------"
echo ""

echo "========================================================"
echo "[2단계] 프론트엔드(React) 패키지 설치 및 실행 시작"
echo "========================================================"
cd frontend

echo "- npm 패키지 설치 중... (잠시만 기다려주세요)"
npm install

echo "- 리액트 개발 서버 실행 중..."
# 리눅스/Mac에서는 새 터미널 창을 띄우는 방식이 환경마다 다르므로 
# 현재 터미널에서 백그라운드로 실행하거나 직접 실행하도록 구성합니다.
npm run dev &

echo ""
echo "--------------------------------------------------------"
echo " [프론트엔드 서버 실행 완료!]"
echo " - 프론트엔드 접속 주소:      http://localhost:5173"
echo "--------------------------------------------------------"
echo ""

echo "========================================================"
echo "모든 서비스가 성공적으로 구동되었습니다!"
echo "========================================================"